#[cfg(windows)]
pub fn clipboard_is_image_only() -> bool {
    use windows_sys::Win32::System::DataExchange::{
        IsClipboardFormatAvailable, RegisterClipboardFormatW,
    };
    // Mixed text/file copies and password-manager/sensitive formats are deliberately ignored.
    unsafe {
        if [1, 13, 15]
            .iter()
            .any(|f| IsClipboardFormatAvailable(*f) != 0)
        {
            return false;
        }
        for name in [
            "ExcludeClipboardContentFromMonitorProcessing",
            "Clipboard Viewer Ignore",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            let wide: Vec<u16> = name.encode_utf16().chain(Some(0)).collect();
            let id = RegisterClipboardFormatW(wide.as_ptr());
            if id != 0 && IsClipboardFormatAvailable(id) != 0 {
                return false;
            }
        }
        [2, 8, 17]
            .iter()
            .any(|f| IsClipboardFormatAvailable(*f) != 0)
    }
}

#[cfg(not(windows))]
pub fn clipboard_is_image_only() -> bool {
    false
}
#[cfg(windows)]
pub fn screenshot_folder() -> Option<std::path::PathBuf> {
    use std::os::windows::ffi::OsStringExt;
    use windows_sys::Win32::{
        System::Com::CoTaskMemFree,
        UI::Shell::{FOLDERID_Screenshots, SHGetKnownFolderPath, KF_FLAG_DONT_VERIFY},
    };
    // The known folder respects OneDrive, localization and the user's Location setting.
    unsafe {
        let mut path = std::ptr::null_mut();
        if SHGetKnownFolderPath(
            &FOLDERID_Screenshots,
            KF_FLAG_DONT_VERIFY as u32,
            std::ptr::null_mut(),
            &mut path,
        ) >= 0
            && !path.is_null()
        {
            let mut len = 0;
            while *path.add(len) != 0 {
                len += 1;
            }
            let folder = std::ffi::OsString::from_wide(std::slice::from_raw_parts(path, len));
            CoTaskMemFree(path.cast());
            return Some(folder.into());
        }
    }
    dirs::picture_dir().map(|p| p.join("Screenshots"))
}

#[cfg(not(windows))]
pub fn screenshot_folder() -> Option<std::path::PathBuf> {
    dirs::picture_dir().map(|p| p.join("Screenshots"))
}
#[cfg(windows)]
fn is_input_host_image(path: &std::path::Path) -> bool {
    path.file_name()
        .is_some_and(|name| name.eq_ignore_ascii_case("TextInputHost.exe"))
}
#[cfg(windows)]
fn is_system_input_window(window: windows_sys::Win32::Foundation::HWND) -> bool {
    use std::os::windows::ffi::OsStringExt;
    use windows_sys::Win32::{
        Foundation::CloseHandle,
        System::Threading::{
            OpenProcess, QueryFullProcessImageNameW, PROCESS_QUERY_LIMITED_INFORMATION,
        },
        UI::WindowsAndMessaging::GetWindowThreadProcessId,
    };
    unsafe {
        let mut process_id = 0;
        GetWindowThreadProcessId(window, &mut process_id);
        let process = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, process_id);
        if process.is_null() {
            return false;
        }
        let mut path = [0u16; 1024];
        let mut length = path.len() as u32;
        let read = QueryFullProcessImageNameW(process, 0, path.as_mut_ptr(), &mut length);
        CloseHandle(process);
        if read == 0 {
            return false;
        }
        let image = std::ffi::OsString::from_wide(&path[..length as usize]);
        is_input_host_image(std::path::Path::new(&image))
    }
}
#[cfg(windows)]
pub fn foreground_is_fullscreen() -> bool {
    use windows_sys::Win32::{
        Foundation::RECT,
        Graphics::Gdi::{
            GetMonitorInfoW, MonitorFromWindow, MONITORINFO, MONITOR_DEFAULTTONEAREST,
        },
        UI::WindowsAndMessaging::{
            GetClassNameW, GetForegroundWindow, GetWindowRect, IsIconic, IsWindowVisible,
        },
    };
    unsafe {
        let window = GetForegroundWindow();
        if window.is_null() || IsWindowVisible(window) == 0 || IsIconic(window) != 0 {
            return false;
        }
        let mut class = [0u16; 128];
        let n = GetClassNameW(window, class.as_mut_ptr(), class.len() as i32);
        let class = String::from_utf16_lossy(&class[..n.max(0) as usize]);
        if ["Progman", "WorkerW", "Shell_TrayWnd"].contains(&class.as_str()) {
            return false;
        }
        let mut rect: RECT = std::mem::zeroed();
        let mut monitor: MONITORINFO = std::mem::zeroed();
        monitor.cbSize = std::mem::size_of::<MONITORINFO>() as u32;
        if GetWindowRect(window, &mut rect) == 0
            || GetMonitorInfoW(
                MonitorFromWindow(window, MONITOR_DEFAULTTONEAREST),
                &mut monitor,
            ) == 0
        {
            return false;
        }
        let area = monitor.rcMonitor;
        let covers_monitor = (rect.left - area.left).abs() <= 2
            && (rect.top - area.top).abs() <= 2
            && (rect.right - area.right).abs() <= 2
            && (rect.bottom - area.bottom).abs() <= 2;
        // Windows' input host can transiently own a monitor-sized foreground
        // HWND after an island closes. It is an input surface, not a fullscreen
        // app. Identify the image, never its localized title or shared UWP class.
        covers_monitor && !is_system_input_window(window)
    }
}

#[cfg(not(windows))]
pub fn foreground_is_fullscreen() -> bool {
    false
}

#[cfg(windows)]
pub fn file_ready_for_copy(path: &std::path::Path) -> bool {
    use std::os::windows::fs::OpenOptionsExt;
    // Permit other readers and rename/delete, but not a currently open writer.
    std::fs::OpenOptions::new()
        .read(true)
        .share_mode(1 | 4)
        .open(path)
        .is_ok()
}

#[cfg(not(windows))]
pub fn file_ready_for_copy(path: &std::path::Path) -> bool {
    path.is_file()
}

/// One immutable virtual-desktop frame. Coordinates and pixels are physical pixels.
pub struct DesktopFrame {
    pub image: image::RgbaImage,
    pub origin_x: i32,
    pub origin_y: i32,
}

#[cfg(windows)]
pub fn capture_desktop() -> crate::library::Result<DesktopFrame> {
    use windows_sys::Win32::{Graphics::Gdi::*, UI::WindowsAndMessaging::*};
    unsafe {
        let x = GetSystemMetrics(SM_XVIRTUALSCREEN);
        let y = GetSystemMetrics(SM_YVIRTUALSCREEN);
        let width = GetSystemMetrics(SM_CXVIRTUALSCREEN);
        let height = GetSystemMetrics(SM_CYVIRTUALSCREEN);
        if width <= 0 || height <= 0 || i64::from(width) * i64::from(height) > 80_000_000 {
            return Err("桌面尺寸无效或超过 8000 万像素。".into());
        }
        let screen = GetDC(std::ptr::null_mut());
        if screen.is_null() {
            return Err("无法读取桌面设备。".into());
        }
        let memory = CreateCompatibleDC(screen);
        let bitmap = CreateCompatibleBitmap(screen, width, height);
        if memory.is_null() || bitmap.is_null() {
            if !bitmap.is_null() {
                DeleteObject(bitmap);
            }
            if !memory.is_null() {
                DeleteDC(memory);
            }
            ReleaseDC(std::ptr::null_mut(), screen);
            return Err("无法分配截图缓冲区。".into());
        }
        let previous = SelectObject(memory, bitmap);
        let copied = BitBlt(
            memory,
            0,
            0,
            width,
            height,
            screen,
            x,
            y,
            SRCCOPY | CAPTUREBLT,
        );
        // GetDIBits requires the bitmap to be deselected first.
        SelectObject(memory, previous);
        let mut info: BITMAPINFO = std::mem::zeroed();
        info.bmiHeader.biSize = std::mem::size_of::<BITMAPINFOHEADER>() as u32;
        info.bmiHeader.biWidth = width;
        info.bmiHeader.biHeight = -height;
        info.bmiHeader.biPlanes = 1;
        info.bmiHeader.biBitCount = 32;
        info.bmiHeader.biCompression = BI_RGB;
        let mut pixels = vec![0u8; width as usize * height as usize * 4];
        let lines = if copied != 0 {
            GetDIBits(
                memory,
                bitmap,
                0,
                height as u32,
                pixels.as_mut_ptr().cast(),
                &mut info,
                DIB_RGB_COLORS,
            )
        } else {
            0
        };
        DeleteObject(bitmap);
        DeleteDC(memory);
        ReleaseDC(std::ptr::null_mut(), screen);
        if lines != height {
            return Err("Windows 未能完成桌面截图。".into());
        }
        for pixel in pixels.as_chunks_mut::<4>().0 {
            pixel.swap(0, 2);
            pixel[3] = 255;
        }
        let image = image::RgbaImage::from_raw(width as u32, height as u32, pixels)
            .ok_or("截图缓冲区无效")?;
        Ok(DesktopFrame {
            image,
            origin_x: x,
            origin_y: y,
        })
    }
}

#[cfg(not(windows))]
pub fn capture_desktop() -> crate::library::Result<DesktopFrame> {
    Err("原生截图目前仅支持 Windows。".into())
}

#[cfg(windows)]
pub fn set_opacity(hwnd: isize, opacity: f64) -> crate::library::Result<()> {
    use windows_sys::Win32::UI::WindowsAndMessaging::*;
    unsafe {
        let hwnd = hwnd as windows_sys::Win32::Foundation::HWND;
        let style = GetWindowLongW(hwnd, GWL_EXSTYLE);
        SetWindowLongW(hwnd, GWL_EXSTYLE, style | WS_EX_LAYERED as i32);
        if SetLayeredWindowAttributes(hwnd, 0, (opacity * 255.0).round() as u8, LWA_ALPHA) == 0 {
            return Err("无法调整贴图透明度。".into());
        }
    }
    Ok(())
}

/// Windows 11 can add a DWM border/corner treatment independently of the webview.
/// These optional hints are unsupported on Windows 10; shadow(false) remains the
/// cross-version base. No image pixels, alpha or color saturation are modified.
pub fn remove_pin_frame(window: &tauri::WebviewWindow) {
    #[cfg(windows)]
    if let Ok(hwnd) = window.hwnd() {
        use windows_sys::Win32::Graphics::Dwm::{
            DwmSetWindowAttribute, DWMWA_BORDER_COLOR, DWMWA_WINDOW_CORNER_PREFERENCE,
            DWMWCP_DONOTROUND,
        };
        let border: u32 = 0xffff_fffe; // DWMWA_COLOR_NONE
        let corner: i32 = DWMWCP_DONOTROUND;
        unsafe {
            let _ = DwmSetWindowAttribute(
                hwnd.0 as _,
                DWMWA_BORDER_COLOR as u32,
                (&border as *const u32).cast(),
                std::mem::size_of::<u32>() as u32,
            );
            let _ = DwmSetWindowAttribute(
                hwnd.0 as _,
                DWMWA_WINDOW_CORNER_PREFERENCE as u32,
                (&corner as *const i32).cast(),
                std::mem::size_of::<i32>() as u32,
            );
        }
    }
    #[cfg(not(windows))]
    let _ = window;
}

/// Disable DWM hide/show/resize transitions on this HWND only. The capture
/// overlay keeps this enabled for its entire lifetime, including first show.
#[cfg(windows)]
pub fn set_capture_transitions(
    window: &tauri::WebviewWindow,
    disabled: bool,
) -> crate::library::Result<()> {
    use windows_sys::Win32::Graphics::Dwm::{
        DwmSetWindowAttribute, DWMWA_TRANSITIONS_FORCEDISABLED,
    };
    let disabled: i32 = i32::from(disabled);
    let hwnd = window.hwnd().map_err(|e| e.to_string())?.0;
    let result = unsafe {
        DwmSetWindowAttribute(
            hwnd as _,
            DWMWA_TRANSITIONS_FORCEDISABLED as u32,
            (&disabled as *const i32).cast(),
            std::mem::size_of::<i32>() as u32,
        )
    };
    if result < 0 {
        return Err("无法同步 Windows 窗口动画，请重试截图。".into());
    }
    Ok(())
}
#[cfg(not(windows))]
pub fn set_capture_transitions(
    _window: &tauri::WebviewWindow,
    _disabled: bool,
) -> crate::library::Result<()> {
    Ok(())
}

/// Called off the UI thread, after its hide operations have completed. Flush the
/// compositor before reading GDI pixels; a fixed timer alone can capture a fade.
#[cfg(windows)]
pub fn wait_for_compositor() -> crate::library::Result<()> {
    flush_compositor()?;
    // Allow newly exposed windows to finish their paint, then wait for that frame.
    std::thread::sleep(std::time::Duration::from_millis(50));
    flush_compositor()
}
#[cfg(windows)]
pub fn flush_compositor() -> crate::library::Result<()> {
    if unsafe { windows_sys::Win32::Graphics::Dwm::DwmFlush() } < 0 {
        return Err("Windows 桌面合成尚未就绪，请重试截图。".into());
    }
    Ok(())
}
#[cfg(not(windows))]
pub fn flush_compositor() -> crate::library::Result<()> {
    Ok(())
}
#[cfg(not(windows))]
pub fn wait_for_compositor() -> crate::library::Result<()> {
    Ok(())
}

/// Resolve the actual file before handing it to another process. A desktop app
/// launched by an MSIX host can see a virtual AppData path that Explorer cannot.
/// Windows canonicalize uses GetFinalPathNameByHandle, including VFS redirection.
pub fn external_file_path(path: &std::path::Path) -> crate::library::Result<std::path::PathBuf> {
    if !path.is_file() {
        return Err("文件已不存在，无法打开或拖出。".into());
    }
    let physical = path
        .canonicalize()
        .map_err(|_| "无法解析文件的实际位置，请稍后重试。".to_string())?;
    #[cfg(windows)]
    return Ok(shell_path(&physical));
    #[cfg(not(windows))]
    Ok(physical)
}

#[cfg(windows)]
pub(crate) fn shell_path(path: &std::path::Path) -> std::path::PathBuf {
    use std::os::windows::ffi::{OsStrExt, OsStringExt};
    let wide: Vec<u16> = path.as_os_str().encode_wide().collect();
    // Shell/OLE consumers expect ordinary DOS/UNC paths. Preserve all filename
    // code units (including Unicode) and leave device/volume namespaces intact.
    let normal = if wide.starts_with(&[92, 92, 63, 92, 85, 78, 67, 92]) {
        [vec![92, 92], wide[8..].to_vec()].concat()
    } else if wide.starts_with(&[92, 92, 63, 92])
        && wide.len() >= 7
        && wide[4] <= 127
        && (wide[4] as u8).is_ascii_alphabetic()
        && wide[5] == 58
        && wide[6] == 92
    {
        wide[4..].to_vec()
    } else {
        wide
    };
    std::ffi::OsString::from_wide(&normal).into()
}

/// Shell PIDLs avoid Explorer command-line quoting/parsing ambiguities (spaces,
/// commas, Unicode). The caller gives this operation a dedicated background thread.
#[cfg(windows)]
pub fn reveal_path(path: &std::path::Path) -> crate::library::Result<()> {
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::{
        System::Com::{CoInitializeEx, CoTaskMemFree, CoUninitialize, COINIT_APARTMENTTHREADED},
        UI::Shell::{SHOpenFolderAndSelectItems, SHParseDisplayName},
    };
    let path = external_file_path(path)?;
    let wide: Vec<u16> = path.as_os_str().encode_wide().chain(Some(0)).collect();
    unsafe {
        if CoInitializeEx(std::ptr::null(), COINIT_APARTMENTTHREADED as u32) < 0 {
            return Err("无法初始化资源管理器接口。".into());
        }
        struct ComGuard;
        impl Drop for ComGuard {
            fn drop(&mut self) {
                unsafe {
                    CoUninitialize();
                }
            }
        }
        let _com = ComGuard;
        let mut pidl = std::ptr::null_mut();
        let parsed = SHParseDisplayName(
            wide.as_ptr(),
            std::ptr::null_mut(),
            &mut pidl,
            0,
            std::ptr::null_mut(),
        );
        if parsed < 0 || pidl.is_null() {
            return Err("Windows 无法定位这张图片。".into());
        }
        // cidl=0 means an absolute single-item PIDL: open its parent and select it.
        let opened = SHOpenFolderAndSelectItems(pidl, 0, std::ptr::null(), 0);
        CoTaskMemFree(pidl.cast());
        if opened < 0 {
            return Err("无法在资源管理器中显示图片，请稍后重试。".into());
        }
    }
    Ok(())
}

#[cfg(test)]
mod external_path_tests {
    use super::*;

    #[cfg(windows)]
    #[test]
    fn input_host_is_identified_by_image_not_localized_title_or_shared_window_class() {
        use std::path::Path;
        assert!(is_input_host_image(Path::new(
            r"C:\Windows\SystemApps\MicrosoftWindows.Client.CBS_cw5n1h2txyewy\TextInputHost.exe"
        )));
        assert!(is_input_host_image(Path::new(
            r"C:\Windows\SystemApps\Package\TEXTINPUTHOST.EXE"
        )));
        for image in [
            r"C:\Apps\Player.exe",
            r"C:\Apps\MyTextInputHost.exe",
            r"C:\Apps\TextInputHost.exe.bak",
        ] {
            assert!(!is_input_host_image(Path::new(image)));
        }
    }

    #[test]
    fn external_path_keeps_existing_unicode_file_and_rejects_missing_file() {
        let temp = tempfile::tempdir_in(env!("CARGO_MANIFEST_DIR")).unwrap();
        let file = temp.path().join("截图, with spaces.png");
        std::fs::write(&file, b"external-file").unwrap();
        let external = external_file_path(&file).unwrap();
        assert!(external.is_absolute());
        assert_eq!(std::fs::read(&external).unwrap(), b"external-file");
        assert_eq!(external.file_name(), file.file_name());
        assert!(external_file_path(&temp.path().join("missing.png")).is_err());
        assert!(external_file_path(temp.path()).is_err());
    }

    #[cfg(windows)]
    #[test]
    fn shell_paths_preserve_dos_unc_unicode_and_device_namespaces() {
        use std::path::Path;
        for (physical, external) in [
            (
                r"\\?\C:\Users\User\LocalCache\截图, a.png",
                r"C:\Users\User\LocalCache\截图, a.png",
            ),
            (
                r"\\?\UNC\server\share\截图, a.png",
                r"\\server\share\截图, a.png",
            ),
            (r"\\?\Volume{example}\a.png", r"\\?\Volume{example}\a.png"),
            (r"C:\normal\a.png", r"C:\normal\a.png"),
        ] {
            assert_eq!(shell_path(Path::new(physical)), Path::new(external));
        }
    }
}
