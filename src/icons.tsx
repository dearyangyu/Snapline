/** Keep existing semantic names at call sites. Import one Phosphor module per
 * icon; SVG stroke-width styling from the former family must not distort it. */
function adapted(Component: Icon): Icon {
  const Result = forwardRef<SVGSVGElement, IconProps>(({ weight, strokeWidth, fill, size = 20, ...props }, ref) =>
    <Component {...props} ref={ref} size={size} weight={weight ?? (fill === 'currentColor' ? 'fill' : Number(strokeWidth) >= 2.4 ? 'bold' : 'regular')} />);
  Result.displayName = `App${Component.displayName || 'Icon'}`;
  return Result;
}
